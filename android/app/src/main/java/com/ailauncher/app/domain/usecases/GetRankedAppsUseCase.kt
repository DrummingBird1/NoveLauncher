/**
 * v7 FIX #7: Now correctly injects NotificationDao + AppPredictionEngine.
 * Combines installed apps + usage data + AI scoring + notification badges.
 *
 * v10: also feeds the ranking situational context (ContextSignals) and the
 * learned "shown vs. tapped" feedback (SuggestionFeedbackRepository), applies
 * the selected icon pack, reports the user's other profiles, and keeps
 * Private Space apps out of the shared lists — Android's guidance is that
 * they never surface in suggestions, folders or search; the Apps page shows
 * them in their own section only while the space is unlocked.
 */
@Singleton
class GetRankedAppsUseCase @Inject constructor(
    private val installedAppsRepo: InstalledAppsRepository,
    private val usageStatsRepo: UsageStatsRepository,
    private val categoryProvider: AppCategoryProvider,
    private val notificationDao: NotificationDao,
    private val predictionEngine: AppPredictionEngine,
    private val settingsRepo: SettingsRepository,
    private val feedbackRepo: SuggestionFeedbackRepository,
    private val contextSignals: ContextSignals,
    private val jewishCalendar: JewishCalendarService
) {
    data class Result(
        val rankedApps: List<RankedApp>,
        val smartFolders: List<SmartFolder>,
        val hasUsagePermission: Boolean,
        val privateSpaceApps: List<RankedApp> = emptyList(),
        val profiles: List<ProfileState> = emptyList()
    )

    suspend fun execute(): Result {
        val hasPermission = usageStatsRepo.hasPermission()
        val appearance = settingsRepo.appearanceFlow.first()
        val apps = installedAppsRepo.getInstalledApps(appearance.iconPackPackage)
        val snapshots = if (hasPermission) usageStatsRepo.getUsageSnapshots() else emptyMap()

        // Get notification counts (v7 — feature #15). Suppressed entirely while
        // badges are off or snoozed — or, v10, while Shabbat mode is active —
        // rather than computing them and hiding them at render time: cheaper,
        // and keeps "snoozed" meaning what it says.
        val badgesSuppressed = !appearance.showNotificationBadges ||
            appearance.badgeSnoozedUntil > System.currentTimeMillis() ||
            jewishCalendar.isShabbatModeActive(appearance.jewishCalendar)
        val notificationCounts = if (badgesSuppressed) emptyMap() else try {
            notificationDao.getAppsWithUnread().associateWith { pkg ->
                notificationDao.get(pkg)?.unreadCount ?: 0
            }
        } catch (_: Exception) { emptyMap() }

        val ranked = categoryProvider.rankApps(apps, snapshots, contextSignals.current(), feedbackRepo.counts())
            .map { it.copy(notificationCount = notificationCounts[it.app.packageName] ?: 0) }
        val (privateApps, shared) = ranked.partition { it.app.profile == AppProfile.PRIVATE }

        val folders = categoryProvider.autoGroup(shared).map { (cat, list) ->
            SmartFolder(category = cat, apps = list, isAutoGenerated = true)
        }

        return Result(
            rankedApps = shared,
            smartFolders = folders,
            hasUsagePermission = hasPermission,
            privateSpaceApps = privateApps.sortedBy { it.app.label.lowercase() },
            profiles = installedAppsRepo.getProfiles()
        )
    }
}
